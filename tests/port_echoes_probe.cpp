struct Writer {
  std::vector<uint8_t> b;
  void U8(uint8_t v) { b.push_back(v); }
  void U16(uint16_t v) {
    b.push_back(uint8_t(v >> 8));
    b.push_back(uint8_t(v));
  }
  void U32(uint32_t v) {
    for (int s = 24; s >= 0; s -= 8) {
      b.push_back(uint8_t(v >> s));
    }
  }
  void F32(float f) {
    uint32_t v;
    std::memcpy(&v, &f, 4);
    U32(v);
  }
  void Str(const std::string& s) {
    b.insert(b.end(), s.begin(), s.end());
    b.push_back(0);
  }
  void Bytes(const uint8_t* p, size_t n) { b.insert(b.end(), p, p + n); }
};

void TestLzo() {
  const size_t total = 0x4000 + 0x1234;
  const std::vector<uint8_t> expect = Input(total);
  // Each segment alone.
  std::vector<uint8_t> out(0x4000);
  Check(PortLzo::Decompress1x(kSegment0, sizeof(kSegment0), out.data(), 0x4000) &&
            std::memcmp(out.data(), expect.data(), 0x4000) == 0,
        "segment 0 inflates to its input");
  out.assign(0x1234, 0);
  Check(PortLzo::Decompress1x(kSegment1, sizeof(kSegment1), out.data(), 0x1234) &&
            std::memcmp(out.data(), expect.data() + 0x4000, 0x1234) == 0,
        "segment 1 inflates to its input");
  // Short or cut: refused.
  Check(!PortLzo::Decompress1x(kSegment1, sizeof(kSegment1) - 1, out.data(), 0x1234), "a cut stream is refused");
  Check(!PortLzo::Decompress1x(kSegment1, sizeof(kSegment1), out.data(), 0x1233), "a wrong size is refused");

  // As Echoes stores a resource: size, segments, then the PAK's 0xFF padding.
  Writer w;
  w.U32(uint32_t(total));
  w.U16(uint16_t(sizeof(kSegment0)));
  w.Bytes(kSegment0, sizeof(kSegment0));
  w.U16(uint16_t(sizeof(kSegment1)));
  w.Bytes(kSegment1, sizeof(kSegment1));
  for (int i = 0; i < 29; ++i) {
    w.U8(0xFF);
  }
  std::vector<uint8_t> whole;
  Check(PortLzo::DecompressSegmented(w.b.data(), w.b.size(), whole) && whole == expect,
        "a segmented resource inflates whole, padding ignored");

  // A stored segment (negative size) between compressed ones.
  Writer s;
  const size_t storedSize = 100;
  s.U32(uint32_t(0x4000 + storedSize));
  s.U16(uint16_t(sizeof(kSegment0)));
  s.Bytes(kSegment0, sizeof(kSegment0));
  s.U16(uint16_t(-int16_t(storedSize)));
  s.Bytes(expect.data() + 0x4000, storedSize);
  Check(PortLzo::DecompressSegmented(s.b.data(), s.b.size(), whole) && whole.size() == 0x4000 + storedSize &&
            std::memcmp(whole.data(), expect.data(), whole.size()) == 0,
        "a stored segment is copied as it is");

  // A corrupt segment is refused, not misread.
  std::vector<uint8_t> bad = w.b;
  bad[4 + 2 + 40] ^= 0x5A;
  std::vector<uint8_t> junk;
  const bool badOk = PortLzo::DecompressSegmented(bad.data(), bad.size(), junk);
  Check(!badOk || junk != expect, "a corrupt segment does not come out as the original");
}

void WriteBone(Writer& w, uint32_t id, uint32_t parent, float x, float y, float z, bool echoes, float rotW) {
  w.U32(id);
  w.U32(parent);
  w.F32(x);
  w.F32(y);
  w.F32(z);
  if (echoes) {
    const float rotations[2][4] = {{rotW, rotW == 1.f ? 0.f : 0.6f, 0.f, 0.f}, {1.f, 0.f, 0.f, 0.f}};
    for (const auto& q : rotations) {
      for (float v : q) {
        w.F32(v);
      }
    }
  }
  w.U32(1);
  w.U32(parent);
}

