void WritePas(Writer& w) {
  w.U32(0x50415334); // PAS4
  w.U32(1);          // states
  w.U32(0);          // default
  w.U32(7);          // state id
  w.U32(5);          // parms: one of each type
  w.U32(2);          // animations
  for (uint32_t type = 0; type < 5; ++type) {
    w.U32(type);
    w.U32(0);
    w.F32(1.f);
    if (type == 3) {
      w.U8(0);
      w.U8(1);
    } else {
      w.U32(0);
      w.U32(1);
    }
  }
  for (uint32_t a = 0; a < 2; ++a) {
    w.U32(a);
    for (uint32_t type = 0; type < 5; ++type) {
      if (type == 3) {
        w.U8(1);
      } else {
        w.U32(a);
      }
    }
  }
}

void WriteCharacter(Writer& w, uint16_t version, const std::string& name, uint32_t skeleton,
                    const std::vector<std::string>& anims) {
  w.U32(0);
  w.U16(version);
  w.Str(name);
  w.U32(0x11111111);
  w.U32(0x22222222);
  w.U32(skeleton);
  w.U32(uint32_t(anims.size()));
  for (size_t i = 0; i < anims.size(); ++i) {
    w.U32(uint32_t(i));
    if (version < 10) {
      w.Str("");
    }
    w.Str(anims[i]);
  }
  WritePas(w);
  const int lists = 3 + (version > 5) + (version >= 10);
  for (int i = 0; i < lists; ++i) {
    w.U32(1);
    w.U32(0xABCD0000u + uint32_t(i));
  }
  w.U32(0);
  if (version >= 10) {
    w.U32(0);
  }
  w.U32(1); // AABBs
  w.Str("Run");
  for (int i = 0; i < 6; ++i) {
    w.F32(float(i));
  }
  w.U32(1); // effects
  w.Str("Footstep");
  w.U32(1);
  w.Str("Dust");
  w.U32(0x50415254);
  w.U32(0x1234);
  w.Str("Toe_L");
  w.F32(1.f);
  w.U32(0);
  w.U32(0);
  w.U32(0x33333333); // frozen model
  w.U32(0x44444444);
  w.U32(2); // animation ids
  w.U32(0);
  w.U32(1);
  if (version >= 10) {
    w.U32(0x55555555);
    w.U8(1);
    w.U32(1);
    w.U32(0);
    for (int i = 0; i < 6; ++i) {
      w.F32(float(i));
    }
  }
}

